"""Prove the guards are not green by accident: break each one, watch the tests fail, restore.

For every mutation: copy the file to a backup, apply the mutation, run the tests
(they MUST fail), restore the file from the backup copy (never from git), and
check it is byte-identical. Finally the whole suite must pass again.
Writes mutation.md (generated).

    python scripts/mutation_check.py
"""
from __future__ import annotations

import datetime as dt
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

MUTATIONS = [
    ("nomenclature check disabled", "structreq/schema.py",
     "if v not in load_catalog().codes:", "if False:"),
    ("PII check on model output disabled", "structreq/schema.py",
     "    if value and find_pii(value):", "    if False:"),
    ("phone/ID pattern broken", "structreq/pii.py",
     r'("PHONE_OR_ID", re.compile(r"', r'("PHONE_OR_ID", re.compile(r"(?!)'),
    ("name rule (first-name list) removed", "structreq/pii.py",
     "    found.extend(_name_findings(text))", "    pass"),
    ("send guard removed", "structreq/pipeline.py",
     '    assert_no_pii(*(m["content"] for m in messages))', "    pass"),
    ("repair no longer bounded", "structreq/pipeline.py",
     "for attempt in range(1 + max_repairs):", "for attempt in range(3 + max_repairs):"),
]


def pytest() -> int:
    env = dict(os.environ, PYTEST_DISABLE_PLUGIN_AUTOLOAD="1")
    return subprocess.run([sys.executable, "-m", "pytest", "-q", "-x", "-p", "no:cacheprovider", "tests"],
                          cwd=ROOT, env=env, capture_output=True, text=True).returncode


def main() -> int:
    if pytest() != 0:
        print("the suite must be green before mutating")
        return 1
    rows, ok = [], True
    backup_dir = Path(tempfile.mkdtemp(prefix="mutation-backup-"))
    for label, rel, old, new in MUTATIONS:
        path = ROOT / rel
        backup = backup_dir / (rel.replace("/", "__") + ".bak")
        shutil.copy2(path, backup)
        src = path.read_text(encoding="utf-8")
        assert src.count(old) == 1, f"mutation target not found exactly once: {label}"
        path.write_text(src.replace(old, new), encoding="utf-8")
        try:
            code = pytest()
        finally:
            shutil.copy2(backup, path)                      # restore from the copy, not from git
        restored = path.read_bytes() == backup.read_bytes()
        caught = code != 0
        ok &= caught and restored
        rows.append((label, rel, "red (caught)" if caught else "GREEN - NOT CAUGHT", "yes" if restored else "NO"))
        print(f"{label:40} {'caught' if caught else 'NOT CAUGHT'}")
    final = pytest()
    ok &= final == 0
    shutil.rmtree(backup_dir)
    lines = ["# Mutation check", "",
             f"Generated by `python scripts/mutation_check.py` on {dt.date.today().isoformat()}.",
             "Each guard is broken on purpose; the test suite must turn red. The file is then",
             "restored from a backup copy (not from git) and compared byte for byte.", "",
             "| Mutation | File | Test suite | Restored |", "|---|---|---|---|"]
    lines += [f"| {a} | `{b}` | {c} | {d} |" for a, b, c, d in rows]
    lines += ["", f"Suite after restoring everything: {'green' if final == 0 else 'RED'}.", ""]
    (ROOT / "mutation.md").write_text("\n".join(lines), encoding="utf-8")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
